// Turns the Material Design Icons package into the one gzipped file the panel
// ships beside the SF Symbol file.
//
// Same shape and same reasoning as build-icons.mjs: Home Assistant serves
// static files uncompressed, so the compression is part of the asset, and the
// panel unzips it with `DecompressionStream`. Only the path and the viewBox
// survive; an MDI file is otherwise an `id` attribute and an XML namespace.
//
// The source is a dependency rather than a directory to point at, because MDI
// ships as `@mdi/svg` and the version is what pins which glyphs exist. Keys are
// the names a document carries (`mdi:flash`), prefix included, so a symbol
// string is looked up as written.
//
// Usage:
//   npm run build:mdi
//   node build-mdi-icons.mjs [--src <dir of *.svg>]

import { createHash } from "node:crypto";
import { gzipSync } from "node:zlib";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { optimize } from "svgo";

const DEFAULT_SRC = "node_modules/@mdi/svg/svg";
const OUT = "../custom_components/wrist_assistant/frontend/mdi-icons.json.gz";
/** Home Assistant serves this route with a month of cache, so the panel asks
 * for the file by content. Generated, not hand edited. */
const DIGEST_OUT = "src/mdi-digest.ts";

/** Two decimals moves any point at most 0.05 user units, well under a pixel on
 * a 24px tile. The same figure build-icons.mjs uses, for the same reason. */
const PRECISION = 2;

function arg(name) {
  const i = process.argv.indexOf(name);
  return i === -1 ? undefined : process.argv[i + 1];
}

const src = arg("--src") ?? DEFAULT_SRC;

const svgoConfig = {
  multipass: true,
  floatPrecision: PRECISION,
  plugins: [
    // The viewBox is the only thing that says how big the drawing is, and the
    // preset drops it by default.
    { name: "preset-default", params: { overrides: { removeViewBox: false } } },
    { name: "convertPathData", params: { floatPrecision: PRECISION, utilizeAbsolute: true } },
  ],
};

const PATH_RE = /<path[^>]*\bd="([^"]+)"/g;
const VIEWBOX_RE = /viewBox="([^"]+)"/;

const icons = {};
const skipped = [];

let files;
try {
  files = readdirSync(src).sort();
} catch {
  console.error(`build-mdi-icons: cannot read ${src}. Run npm install first, or pass --src.`);
  process.exit(1);
}

for (const file of files) {
  if (!file.endsWith(".svg")) continue;
  const name = `mdi:${file.slice(0, -4)}`;

  const optimized = optimize(readFileSync(join(src, file), "utf8"), svgoConfig).data;
  const paths = [...optimized.matchAll(PATH_RE)].map((m) => m[1]);
  const viewBox = VIEWBOX_RE.exec(optimized)?.[1];
  if (paths.length === 0 || !viewBox) {
    skipped.push(name);
    continue;
  }
  // Several subpaths concatenate into one `d` without changing the drawing.
  icons[name] = [paths.join(" "), viewBox];
}

if (skipped.length > 0) console.warn(`build-mdi-icons: no drawable path in ${skipped.length} file(s)`);

const json = Buffer.from(JSON.stringify(icons));
const gz = gzipSync(json, { level: 9 });
writeFileSync(OUT, gz);

const digest = createHash("sha256").update(gz).digest("hex").slice(0, 12);
writeFileSync(
  DIGEST_OUT,
  `// Generated by build-mdi-icons.mjs. Do not edit.\nexport const MDI_DIGEST = ${JSON.stringify(digest)};\n`
);

const kb = (n) => `${(n / 1024).toFixed(1)} kB`;
console.log(
  `build-mdi-icons: ${Object.keys(icons).length} icons  ${kb(json.length)} → ${kb(gz.length)} gzipped  (${digest})`
);
console.log("build-mdi-icons: run `npm run build` next so the panel picks up the new digest");
