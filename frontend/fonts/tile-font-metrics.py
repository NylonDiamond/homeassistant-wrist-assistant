"""Writes src/tile-font-metrics.ts from the four Inter cuts in this folder.

Run from frontend/:
    uvx --with uharfbuzz --with fonttools python fonts/tile-font-metrics.py

The widths are the fonts' own advances, shaped by HarfBuzz with kerning on,
as CoreText draws them in the apps. Ligatures and contextual forms are off:
a measured run is one word or name, where they change next to nothing.
"""
import json
import uharfbuzz as hb
from fontTools.ttLib import TTFont

CUTS = {"regular": "inter-regular.woff2", "medium": "inter-medium.woff2", "semibold": "inter-semibold.woff2", "bold": "inter-bold.woff2"}
EXTRA = "—–…°·‘’“”•€×÷−"
CANDIDATES = [chr(c) for c in range(0x20, 0x7F)] + [chr(c) for c in range(0xA0, 0x100)] + list(EXTRA)
ASCII = [chr(c) for c in range(0x20, 0x7F)]


def b36(n):
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"
    sign = "-" if n < 0 else ""
    n = abs(n)
    out = ""
    while True:
        out = digits[n % 36] + out
        n //= 36
        if n == 0:
            return sign + out


def main():
    first = TTFont("fonts/" + CUTS["regular"])
    cmap = first.getBestCmap()
    chars = [c for c in CANDIDATES if ord(c) in cmap]
    upm = first["head"].unitsPerEm
    advances = {}
    kerning = {}
    for weight, file in CUTS.items():
        font = TTFont("fonts/" + file)
        font.flavor = None
        import io
        raw = io.BytesIO()
        font.save(raw)
        face = hb.Face(raw.getvalue())
        hbfont = hb.Font(face)

        def width(s):
            buf = hb.Buffer()
            buf.add_str(s)
            buf.guess_segment_properties()
            hb.shape(hbfont, buf, {"kern": True, "liga": False, "calt": False})
            return sum(p.x_advance for p in buf.glyph_positions)

        adv = {c: width(c) for c in chars}
        advances[weight] = ",".join(b36(adv[c]) for c in chars)
        pairs = []
        for a in ASCII:
            for b in ASCII:
                d = width(a + b) - adv[a] - adv[b]
                if d:
                    pairs.append(a + b + b36(d))
        kerning[weight] = ",".join(pairs)
    lines = [
        "// Generated by fonts/tile-font-metrics.py from the four Inter cuts the",
        "// apps bundle. Do not edit by hand.",
        "",
        "/** The font's units to an em. */",
        f"export const TILE_FONT_UNITS_PER_EM = {upm};",
        "",
        "/** The characters with an advance, in the order of each weight's list. */",
        f"export const TILE_FONT_CHARS = {json.dumps(''.join(chars), ensure_ascii=False)};",
        "",
        "/** Each weight's advances in font units, base 36, comma separated. */",
        "export const TILE_FONT_ADVANCES: Readonly<Record<\"regular\" | \"medium\" | \"semibold\" | \"bold\", string>> = {",
    ]
    for w in CUTS:
        lines.append(f"  {w}: {json.dumps(advances[w])},")
    lines += [
        "};",
        "",
        "/** Each weight's kerning between two printable ASCII characters: the",
        " * pair (two characters, read by position, so either may be a comma), then",
        " * its adjustment in font units, base 36, then a comma. Pairs not listed",
        " * kern by nothing. */",
        "export const TILE_FONT_KERNING: Readonly<Record<\"regular\" | \"medium\" | \"semibold\" | \"bold\", string>> = {",
    ]
    for w in CUTS:
        lines.append(f"  {w}: {json.dumps(kerning[w])},")
    lines += ["};", ""]
    open("src/tile-font-metrics.ts", "w").write("\n".join(lines))


main()
